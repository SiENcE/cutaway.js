// Build an atlas: pack pxl output (sprites, scenes, animation strips) into as few PNG pages as
// possible and write one script that registers them with Cutaway.assets (pages as data URIs, so the
// game loads from file:// and the canvas stays readable).
//   node tools/build-atlas.mjs <pxl-out-dir>... <out.js> [--only name1,prefix_*] [--max 1024] [--png page.png]
// Reads <dir>/sprites/*.png, <dir>/scenes/*.png and <dir>/anims/*.png + .json (Aseprite style), and
// <name>.anchor.json next to a sprite (cut-outs placed in their room, see cutout.mjs).
// --png also writes the pages as files (page.png, page_2.png, ...) to look at.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { decode, encode } from "./lib/png.mjs";

const args = process.argv.slice(2);
const take = (n) => { const i = args.indexOf(n); return i >= 0 ? args.splice(i, 2)[1] : null; };
const only = take("--only")?.split(",") ?? null, MAX = Number(take("--max") ?? 1024), pngOut = take("--png");
const out = args.pop();
if (!out || !args.length) { console.error("usage: node tools/build-atlas.mjs <pxl-out-dir>... <out.js> [--only a,b_*] [--max 1024] [--png page.png]"); process.exit(2); }
const wanted = (name) => !only || only.some((p) => p.endsWith("*") ? name.startsWith(p.slice(0, -1)) : name === p);
const PAD = 1;

/** @type {{name: string, img: {width: number, height: number, data: Uint8Array}, frames: number[][] | null, anchor: number[] | null, x?: number, y?: number, page?: number}[]} */
const entries = [];
for (const dir of args) {
  for (const kind of ["sprites", "scenes", "anims"]) {
    const d = path.join(dir, kind);
    if (!existsSync(d)) continue;
    for (const f of readdirSync(d).filter((f) => f.endsWith(".png")).sort()) {
      const name = f.slice(0, -4);
      if (!wanted(name)) continue;
      const img = decode(readFileSync(path.join(d, f)));
      let frames = null, anchor = null;
      const anchorFile = path.join(d, name + ".anchor.json");          // written by cutout.mjs
      if (existsSync(anchorFile)) anchor = JSON.parse(readFileSync(anchorFile, "utf8")).anchor;
      const json = path.join(d, name + ".json");
      if (kind === "anims" && existsSync(json)) {
        const j = JSON.parse(readFileSync(json, "utf8"));
        frames = (Array.isArray(j.frames) ? j.frames : Object.values(j.frames)).map((q) => [q.frame.x, q.frame.y, q.frame.w, q.frame.h, q.duration ?? 100]);
      }
      if (img.width + 2 * PAD > MAX) throw new Error(`${name} is ${img.width} px wide, more than --max ${MAX}`);
      entries.push({ name, img, frames, anchor });
    }
  }
}

// shelf packing, tallest first, into pages of at most MAX x MAX
const order = entries.slice().sort((a, b) => b.img.height - a.img.height || b.img.width - a.img.width);
const pages = [];
let page = { w: 0, h: 0 }, x = 0, y = 0, shelf = 0;
for (const e of order) {
  const w = e.img.width + 2 * PAD, h = e.img.height + 2 * PAD;
  if (x + w > MAX) { x = 0; y += shelf; shelf = 0; }
  if (y + h > MAX) { pages.push(page); page = { w: 0, h: 0 }; x = 0; y = 0; shelf = 0; }
  e.x = x + PAD; e.y = y + PAD; e.page = pages.length;
  x += w; shelf = Math.max(shelf, h);
  page.w = Math.max(page.w, x); page.h = Math.max(page.h, y + shelf);
}
if (entries.length) pages.push(page);

const base = path.basename(out, ".js").replace(/[^a-zA-Z0-9_]/g, "_");
const images = {}, anims = {};
pages.forEach((p, i) => {
  const data = new Uint8Array(p.w * p.h * 4);
  for (const e of entries.filter((q) => q.page === i)) {
    for (let r = 0; r < e.img.height; r++) {
      data.set(e.img.data.subarray(r * e.img.width * 4, (r + 1) * e.img.width * 4), ((e.y + r) * p.w + e.x) * 4);
    }
  }
  const png = encode({ width: p.w, height: p.h, data }), pageName = `${base}_atlas${i ? "_" + (i + 1) : ""}`;
  images[pageName] = "data:image/png;base64," + png.toString("base64");
  if (pngOut) writeFileSync(i ? pngOut.replace(/\.png$/, `_${i + 1}.png`) : pngOut, png);
  for (const e of entries.filter((q) => q.page === i)) {
    const frames = e.frames ?? [[0, 0, e.img.width, e.img.height, 100]];
    anims[e.name] = { image: pageName, frames: frames.map(([fx, fy, fw, fh, d]) => [e.x + fx, e.y + fy, fw, fh, d]), anchor: e.anchor };
  }
});

const lines = ["// Generated by tools/build-atlas.mjs. Do not edit.", "Cutaway.assets.pack({", "  images: {"];
for (const [k, v] of Object.entries(images)) lines.push(`    ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
lines.push("  },", "  anims: {");
for (const [k, v] of Object.entries(anims)) {
  lines.push(`    ${JSON.stringify(k)}: { image: ${JSON.stringify(v.image)}, frames: ${JSON.stringify(v.frames)}${v.anchor ? `, anchor: ${JSON.stringify(v.anchor)}` : ""} },`);
}
lines.push("  },", "});", "");
writeFileSync(out, lines.join("\n"));
console.log(`${out}: ${entries.length} images on ${pages.length} page(s) ${pages.map((p) => `${p.w}x${p.h}`).join(", ")}`);
